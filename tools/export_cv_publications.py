#!/usr/bin/env python3
"""Export the homepage's publication records to the two Overleaf CVs."""

import argparse
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import quote


class Publications(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.records = []
        self.record = None
        self.field = None
        self.end_tag = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        classes = attrs.get("class", "").split()
        if tag == "article" and "pub-card" in classes:
            self.record = {"title": "", "authors": "", "meta": "", "honors": "", "type": "", "status": "", "link": ""}
        if self.record is None:
            return
        if tag == "a" and attrs.get("href", "").startswith("https://") and not self.record["link"]:
            self.record["link"] = attrs["href"]
        fields = {"authors": "authors", "meta": "meta", "award-badge": "honors", "type-badge": "type", "status-badge": "status"}
        field = "title" if tag == "h3" else next((fields[c] for c in classes if c in fields), None)
        if field:
            self.field, self.end_tag = field, tag

    def handle_data(self, data):
        if self.record is not None and self.field:
            self.record[self.field] += data

    def handle_endtag(self, tag):
        if self.record is not None and tag == "article":
            self.records.append({key: " ".join(value.split()) for key, value in self.record.items()})
            self.record = None
            self.field = None
        if tag == self.end_tag:
            self.field = None
            self.end_tag = None


def tex(value):
    escapes = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
        "†": r"\textsuperscript{\dag}", "‡": r"\textsuperscript{\ddag}",
        "–": "--", "—": "---", "·": r"\textperiodcentered{}", "×": r"$\times$",
    }
    return "".join(escapes.get(char, char) for char in value)


def tex_url(value):
    # Text glyph macros (especially \textasciitilde{}) alter PDF link targets.
    encoded = quote(value, safe=":/?#[]@!$&'()*+,;=%~_-.")
    escapes = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_"}
    return "".join(escapes.get(char, char) for char in encoded)


def export(source, output):
    parser = Publications()
    parser.feed(source.read_text(encoding="utf-8"))
    if not parser.records or any(not r["authors"] or r["type"] not in {"Conference", "Journal"} for r in parser.records):
        raise ValueError("Every publication must have authors and a Conference/Journal type")
    lines = ["% Generated by tools/export_cv_publications.py; edit index.jemdoc and export again."]
    for kind in ["Conference", "Journal"]:
        lines.append(r"\subsection*{" + kind + " Papers}")
        for record in parser.records:
            if record["type"] != kind:
                continue
            authors = tex(record["authors"]).replace("Mingjun Wang", r"\textbf{Mingjun Wang}")
            meta = record["meta"].removeprefix("Conference paper · ").removeprefix("Journal article · ")
            abbreviations = {
                "Asia and South Pacific Design Automation Conference": "ASP-DAC",
                "International Conference on Computer-Aided Design": "ICCAD",
                "International Conference on Learning Representations": "ICLR",
                "International Conference on Machine Learning": "ICML",
                "International Conference on Computer Design": "ICCD",
                "International Symposium of EDA": "ISEDA",
                "International Test Conference in Asia": "ITC-Asia",
                "Design Automation Conference": "DAC",
                "IEEE Transactions on Computer-Aided Design of Integrated Circuits and Systems": "TCAD",
            }
            for full, short in abbreviations.items():
                if full in meta:
                    meta = meta.replace(full, full + " (" + short + ")", 1)
                    break
            if record["status"]:
                meta += " " + record["status"] + "."
            honors = record["honors"]
            if honors.startswith("Co-first"):
                honors = ""
            title = tex(record["title"])
            if record["link"]:
                title = r"\href{" + tex_url(record["link"]) + "}{" + title + "}"
            lines.append(r"\publication{" + title + "}{" + authors + "}{" + tex(meta) + "}{" + tex(honors) + "}")
    output.write_text("\n\n".join(lines) + "\n", encoding="utf-8")
    print(f"Exported {len(parser.records)} publications to {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parents[1] / "index.jemdoc")
    args = parser.parse_args()
    export(args.source, args.output)
